function poiUploadPlugin(): Plugin {
  return {
    name: 'vite-plugin-poi-upload',
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if (req.method === 'POST' && req.url === '/api/upload-poi-image') {
          let body = '';
          req.on('data', chunk => {
            body += chunk;
          });
          req.on('end', () => {
            try {
              const { filename, base64 } = JSON.parse(body);
              if (!filename || !base64) {
                res.statusCode = 400;
                res.end(JSON.stringify({ error: 'Missing filename or base64' }));
                return;
              }
              const safeFilename = path.basename(filename);
              const targetDir = path.resolve(__dirname, 'public', 'poi-bg', 'center');
              if (!fs.existsSync(targetDir)) {
                fs.mkdirSync(targetDir, { recursive: true });
              }
              const data = base64.replace(/^data:image\/\w+;base64,/, '');
              const buffer = Buffer.from(data, 'base64');
              const filePath = path.join(targetDir, safeFilename);
              fs.writeFileSync(filePath, buffer);
              res.setHeader('Content-Type', 'application/json');
              res.statusCode = 200;
              res.end(JSON.stringify({ success: true, file: safeFilename, path: `/poi-bg/center/${safeFilename}` }));
            } catch (err) {
              res.statusCode = 500;
              res.end(JSON.stringify({ error: String(err) }));
            }
          });
          return;
        }
        next();
      });
    },
  };
}

